"""rlaif/preference_dataset.py — Task 4.1: Preference Dataset Builder for DPO.

Constructs paired (prompt, chosen, rejected) datasets for Direct Preference Optimization (DPO).
Pairs are generated by contrasting:
1. Validated high-quality curriculum/synthetic targets (chosen).
2. Model failures, quality-gate rejected candidates, or unaligned model completions (rejected).

Outputs JSON-Lines format compatible with HuggingFace TRL and custom DPO trainers:
{"prompt": "...", "chosen": "...", "rejected": "...", "stage": 3, "margin": 1.0}
"""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

logger = logging.getLogger("rlaif.preference_dataset")


def generate_contrastive_rejected(prompt: str, chosen: str, stage: int) -> str:
    """Deterministically generate realistic negative/rejected counterpart for a chosen target."""
    chosen_clean = chosen.strip()

    # Stage 1 (English): Degenerative repetitive looping
    if stage == 1:
        words = chosen_clean.split()
        if len(words) >= 4:
            loop = " ".join(words[:3])
            return f"{chosen_clean} {loop} {loop} {loop}"
        return f"{chosen_clean} and it was and it was and it was"

    # Stage 2 (Summarization): Verbose, extraneous rambling / echoing
    elif stage == 2:
        return f"Regarding the prompt '{prompt}', here is some extra rambling: {chosen_clean} Also I think this is very interesting."

    # Stage 3 (Grammar): Reintroduce common grammatical errors
    elif stage == 3:
        err_text = chosen_clean.replace("doesn't", "don't").replace("doesn't", "dont").replace("was", "were")
        if err_text == chosen_clean:
            err_text = chosen_clean.lower().replace("has", "have")
        return err_text if err_text != chosen_clean else f"{chosen_clean} but he do not care."

    # Stage 4 (Punctuation): Strip all punctuation marks and lowercase
    elif stage == 4:
        stripped = "".join(c for c in chosen_clean if c.isalnum() or c.isspace()).lower()
        return stripped

    # Stage 5 (Conversation): Refusal or unhelpful off-topic response
    else:
        return "I cannot answer this question right now because I am not sure about the facts."


def build_preference_dataset(
    curriculum_dir: str | Path = "data/curriculum",
    output_dir: str | Path = "data/preferences",
    synthetic_file: Optional[str | Path] = "data/synthetic/iter_1.jsonl",
) -> List[Dict[str, Any]]:
    """Generate paired preference dataset across all curriculum stages."""
    curr_path = Path(curriculum_dir)
    out_path = Path(output_dir)
    out_path.mkdir(parents=True, exist_ok=True)

    preference_records: List[Dict[str, Any]] = []

    # 1. Process curriculum files
    for stage in range(1, 6):
        stage_files = list(curr_path.glob(f"stage_{stage}_*.jsonl"))
        if not stage_files:
            continue

        stage_pairs = []
        for sf in stage_files:
            with open(sf, "r", encoding="utf-8") as f:
                for line in f:
                    if not line.strip():
                        continue
                    item = json.loads(line)
                    prompt = item["prompt"]
                    chosen = item["target"]
                    rejected = generate_contrastive_rejected(prompt, chosen, stage=stage)

                    record = {
                        "id": f"pref-s{stage}-{len(preference_records) + len(stage_pairs):04d}",
                        "stage": stage,
                        "prompt": prompt,
                        "chosen": chosen,
                        "rejected": rejected,
                        "source": "curriculum_contrastive",
                        "margin": 1.0,
                    }
                    stage_pairs.append(record)

        # Write per-stage preference file
        stage_out = out_path / f"preferences_stage_{stage}.jsonl"
        with open(stage_out, "w", encoding="utf-8") as f:
            for r in stage_pairs:
                f.write(json.dumps(r) + "\n")

        preference_records.extend(stage_pairs)
        logger.info("Stage %d: Generated %d preference pairs in %s", stage, len(stage_pairs), stage_out)

    # 2. Incorporate synthetic data pairs if present
    if synthetic_file and Path(synthetic_file).exists():
        synth_pairs = []
        with open(synthetic_file, "r", encoding="utf-8") as f:
            for line in f:
                if not line.strip():
                    continue
                item = json.loads(line)
                st = item.get("stage", 1)
                p = item["prompt"]
                c = item["target"]
                r = generate_contrastive_rejected(p, c, stage=st)
                synth_pairs.append({
                    "id": f"pref-synth-{len(preference_records) + len(synth_pairs):04d}",
                    "stage": st,
                    "prompt": p,
                    "chosen": c,
                    "rejected": r,
                    "source": "synthetic_contrastive",
                    "margin": 1.0,
                })
        preference_records.extend(synth_pairs)

    # Write combined master preferences
    master_file = out_path / "preferences_master.jsonl"
    with open(master_file, "w", encoding="utf-8") as f:
        for r in preference_records:
            f.write(json.dumps(r) + "\n")

    logger.info("Saved %d total preference pairs to %s", len(preference_records), master_file)
    return preference_records
